@JdbcTest
@ActiveProfiles("test")
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
class JdbcAnalysisStoreTest {

    @Autowired
    private DataSource dataSource;

    private JdbcAnalysisStore store;

    @BeforeEach
    void setUp() throws Exception {
        Path ddl = Path.of("..", "database", "oracle", "ddl", "07_stock_analysis.sql")
                .toAbsolutePath().normalize();
        String h2CompatibleDdl = Files.readString(ddl)
                .replace(
                        "GENERATED BY DEFAULT ON NULL AS IDENTITY",
                        "GENERATED BY DEFAULT AS IDENTITY"
                );
        new ResourceDatabasePopulator(new ByteArrayResource(
                h2CompatibleDdl.getBytes(StandardCharsets.UTF_8)
        )).execute(dataSource);
        ObjectMapper objectMapper = new ObjectMapper().registerModule(new JavaTimeModule());
        store = new JdbcAnalysisStore(dataSource, objectMapper);
    }

    @Test
    void storesAndReadsCompletedAnalysisUsingOracleSchema() {
        Instant startedAt = Instant.parse("2026-08-14T07:00:00Z");
        LocalDate baseDate = LocalDate.of(2026, 8, 14);
        long runId = store.createRun(new NewAnalysisRun(
                "request-1", "005930", AnalysisMode.SWING, baseDate,
                "analysis-v1", "default-v1", startedAt, false, null
        ));
        DailyCandle candle = new DailyCandle(
                baseDate, amount("70000"), amount("72000"), amount("69500"),
                amount("71000"), 10_000_000L
        );
        AnalysisInput input = new AnalysisInput(
                new StockSnapshot("005930", "삼성전자", "KRX", amount("71000")),
                AnalysisMode.SWING,
                baseDate,
                startedAt,
                List.of(candle),
                List.of(candle),
                List.of(candle),
                Map.of()
        );
        BackdataRecord candleRecord = new BackdataRecord(
                "ka10081", BackdataDatasetType.DAILY_CANDLE, "005930", null,
                "upd_stkpc_tp=1", baseDate, startedAt,
                Map.of(
                        "open", "70000", "high", "72000", "low", "69500",
                        "close", "71000", "volume", "10000000"
                )
        );
        Ka10081Response response = Ka10081Response.builder()
                .stkCd("005930").returnCode(0).returnMsg("정상").build();
        AnalysisSourcePayload source = new AnalysisSourcePayload(
                "ka10081", Ka10081Response.class.getName(), "DAILY_CANDLE",
                Map.of("stk_cd", "005930", "base_dt", "20260814", "upd_stkpc_tp", "1"),
                response, KiwoomContinuation.none(), List.of(candleRecord), startedAt, startedAt
        );
        BackdataRecord weeklyRecord = new BackdataRecord(
                "ka10082", BackdataDatasetType.WEEKLY_CANDLE, "005930", null,
                "upd_stkpc_tp=1", baseDate, startedAt, candleRecord.values()
        );
        AnalysisSourcePayload weeklySource = new AnalysisSourcePayload(
                "ka10082", Ka10081Response.class.getName(), "WEEKLY_CANDLE",
                Map.of("stk_cd", "005930", "base_dt", "20260814", "upd_stkpc_tp", "1"),
                response, KiwoomContinuation.none(), List.of(weeklyRecord), startedAt, startedAt
        );
        BackdataRecord monthlyRecord = new BackdataRecord(
                "ka10083", BackdataDatasetType.MONTHLY_CANDLE, "005930", null,
                "upd_stkpc_tp=1", baseDate, startedAt, candleRecord.values()
        );
        AnalysisSourcePayload monthlySource = new AnalysisSourcePayload(
                "ka10083", Ka10081Response.class.getName(), "MONTHLY_CANDLE",
                Map.of("stk_cd", "005930", "base_dt", "20260814", "upd_stkpc_tp", "1"),
                response, KiwoomContinuation.none(), List.of(monthlyRecord), startedAt, startedAt
        );
        CollectedAnalysisData collected = new CollectedAnalysisData(
                input,
                List.of(source, weeklySource, monthlySource),
                List.of(),
                DataQualityStatus.COMPLETE
        );
        AnalysisResult result = new AnalysisResult(
                "analysis-v1", AnalysisMode.SWING, amount("72.5"),
                List.of(
                        new FactorResult(
                                "DAILY_TECHNICAL", amount("4.5"), amount("72.5"),
                                amount("0.25"), "일봉 상승 추세"
                        ),
                        new FactorResult(
                                "WEEKLY_TECHNICAL", amount("3.5"), amount("75"),
                                amount("0.5"), "주봉 상승 추세"
                        ),
                        new FactorResult(
                                "MONTHLY_TECHNICAL", amount("2.5"), amount("70"),
                                amount("0.25"), "월봉 상승 추세"
                        )
                ),
                new StrategyDecision(
                        "SWING_WATCH", "스윙 관찰", StrategyAction.WATCH, List.of("상승 추세")
                ),
                new TradeScenario(
                        amount("70000"), amount("71000"),
                        List.of(amount("76000"), amount("80000")), amount("67000")
                ),
                List.of()
        );

        store.saveCompleted(runId, collected, result, startedAt.plusSeconds(2));

        var saved = store.findById(runId).orElseThrow();
        assertThat(saved.status()).isEqualTo(AnalysisStatus.COMPLETED);
        assertThat(saved.signalReport()).isNull(); // Historical records remain readable.
        assertThat(saved.tradeJudgment()).isNull();
        assertThat(saved.targetBasis()).isNull();
        assertThat(saved.totalScore()).isEqualByComparingTo("72.5");
        assertThat(saved.targets()).containsExactly(amount("76000"), amount("80000"));
        assertThat(saved.factors()).extracting(factor -> factor.factorCode())
                .containsExactlyInAnyOrder(
                        "DAILY_TECHNICAL", "WEEKLY_TECHNICAL", "MONTHLY_TECHNICAL"
                );
        assertThat(store.findPrices("005930", null, null))
                .singleElement()
                .extracting(price -> price.close())
                .isEqualTo(amount("71000"));
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM an_stock_timeframe_candle", Integer.class
        )).isEqualTo(2);
        assertThat(jdbc.queryForList(
                "SELECT timeframe_code FROM an_stock_timeframe_candle ORDER BY timeframe_code",
                String.class
        )).containsExactly("MONTH", "WEEK");

        long pendingId = store.createRun(new NewAnalysisRun("pending-1", "005930", AnalysisMode.SWING,
                baseDate, "analysis-v6-swing", "swing-signals-v1", startedAt, false, null));
        AnalysisResult pending = new com.example.stockanalysis.engine.factor.internal.SwingSuitabilityEngine().analyze(input);
        var signal = new com.example.stockanalysis.engine.model.TradeSignal("BREAKOUT:2026-08-14", "BREAKOUT",
                com.example.stockanalysis.engine.model.TradeSignal.Side.BUY,
                com.example.stockanalysis.engine.model.TradeSignal.State.CONFIRMED, baseDate, baseDate, 0, 5,
                amount("71000"), amount("70000"), amount("71000"), amount("71500"), "IN_RANGE", null,
                List.of("돌파 조건 확인"));
        var signalReport = new com.example.stockanalysis.engine.model.SignalReport("swing-signals-v1", startedAt,
                "UNKNOWN", "READY", List.of(signal), List.of("자동 주문 아님".repeat(700)));
        pending = new AnalysisResult(pending.engineVersion(), pending.mode(), pending.totalScore(), pending.factors(),
                pending.strategy(), pending.scenario(), pending.warnings(), signalReport);
        var judgment = new com.example.stockanalysis.judgment.TradeJudgmentEngine().evaluate(
                new com.example.stockanalysis.judgment.TradeJudgmentEngine.Input(pending, input.stock().currentPrice(), baseDate, startedAt, "PARTIAL"));
        store.saveCompleted(pendingId, new CollectedAnalysisData(input, List.of(), pending.warnings(),
                DataQualityStatus.PARTIAL), pending, startedAt.plusSeconds(3), judgment);
        var pendingView = store.findById(pendingId).orElseThrow();
        assertThat(pendingView.signalReport()).isEqualTo(signalReport);
        assertThat(pendingView.tradeJudgment()).isEqualTo(judgment);
        assertThat(com.example.stockanalysis.analysis.api.StockAnalysisResponse.from(pendingView).tradeJudgment()).isEqualTo(judgment);
        assertThat(com.example.stockanalysis.analysis.api.StockAnalysisResponse.from(pendingView).signalReport())
                .isEqualTo(signalReport);
        assertThat(pendingView.totalScore()).isNull();
        assertThat(pendingView.scoreGrade()).isNull();
        assertThat(pendingView.entryFrom()).isNull();
        assertThat(pendingView.targets()).isEmpty();
        assertThat(pendingView.factors()).allMatch(f -> f.score() == null && f.contribution() == null);
        assertThat(pendingView.warnings()).isNotEmpty();
        assertThat(com.example.stockanalysis.analysis.api.StockAnalysisResponse.from(pendingView)
                .suitabilityScores().status()).isEqualTo("UNAVAILABLE");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM an_factor_result WHERE data_status = 'MISSING'", Integer.class))
                .isEqualTo(10);
        assertThat(com.example.stockanalysis.analysis.api.StockAnalysisResponse.from(pendingView)
                .swingAssessment().detailCode()).isEqualTo("DATA_MISSING");
        for(var basis:TradeScenario.TargetBasis.values()) {
            var basisRun=store.createRun(new NewAnalysisRun("basis-"+basis,"005930",AnalysisMode.SWING,
                    baseDate,"analysis-v7-swing","swing-signals-v2",startedAt,false,null));
            var scenario=result.scenario();
            var marked=new AnalysisResult("analysis-v7-swing",result.mode(),result.totalScore(),result.factors(),result.strategy(),
                    new TradeScenario(scenario.entryFrom(),scenario.entryTo(),scenario.targets(),scenario.stopLoss(),basis),List.of());
            store.saveCompleted(basisRun,collected,marked,startedAt.plusSeconds(4));
            var loaded=store.findById(basisRun).orElseThrow();
            assertThat(loaded.targetBasis()).isEqualTo(basis);
            assertThat(loaded.withHolding(null).targetBasis()).isEqualTo(basis);
            var responseView=com.example.stockanalysis.analysis.api.StockAnalysisResponse.from(loaded).withHolding(null);
            assertThat(responseView.targetBasis()).isEqualTo(basis);
            assertThat(new ObjectMapper().registerModule(new JavaTimeModule()).valueToTree(responseView).path("targetBasis").asText()).isEqualTo(basis.name());
            assertThat(loaded.warnings()).isEmpty();
        }
    }

    private BigDecimal amount(String value) {
        return new BigDecimal(value);
    }
}
